async def _parse_smartflo_start(websocket) -> dict:
    """Read SmartFlo lifecycle events and extract stream metadata."""
    # Check query params first (some SmartFlo deployments pass IDs here)
    query_stream_id = str(
        websocket.query_params.get("streamSid")
        or websocket.query_params.get("stream_id")
        or ""
    ).strip()
    query_call_id = str(
        websocket.query_params.get("callSid")
        or websocket.query_params.get("call_id")
        or ""
    ).strip()
    query_direction = _normalize_call_direction(
        websocket.query_params.get("direction")
        or websocket.query_params.get("callDirection")
        or ""
    )
    if query_stream_id:
        logger.info("SmartFlo metadata from query params: stream_id={}", bool(query_stream_id))
        return {
            "stream_id": query_stream_id,
            "call_id": query_call_id,
            "direction": query_direction,
        }

    for _ in range(25):
        try:
            message = await asyncio.wait_for(websocket.receive(), timeout=2.0)
        except asyncio.TimeoutError:
            continue
        except Exception:
            logger.exception("Failed waiting for SmartFlo start metadata")
            break

        msg_type = str(message.get("type", "")).strip().lower()
        if msg_type == "websocket.disconnect":
            logger.warning("SmartFlo disconnected before start metadata")
            return {"stream_id": "", "call_id": "", "direction": ""}
        if msg_type != "websocket.receive":
            continue

        raw_text = message.get("text")
        if raw_text is None and message.get("bytes") is not None:
            raw_text = message["bytes"].decode("utf-8", errors="ignore")
        if not raw_text:
            continue

        try:
            data = json.loads(raw_text)
        except json.JSONDecodeError:
            continue

        event = str(data.get("event", "")).strip().lower()
        start = data.get("start") or {}
        if not isinstance(start, dict):
            start = {}

        stream_id = str(
            start.get("streamSid") or data.get("streamSid")
            or start.get("stream_id") or data.get("stream_id") or ""
        ).strip()
        call_id = str(
            start.get("callSid") or data.get("callSid")
            or start.get("call_id") or data.get("call_id") or ""
        ).strip()
        direction = _normalize_call_direction(start.get("direction") or data.get("direction") or "")

        logger.info(
            "SmartFlo event='{}' stream_id={} call_id={} direction={}",
            event,
            bool(stream_id),
            bool(call_id),
            direction or "unknown",
        )

        if stream_id and event in {"connected", "start", "media", "mark", "dtmf", "stop"}:
            return {"stream_id": stream_id, "call_id": call_id, "direction": direction}
        if event == "start":
            return {"stream_id": stream_id, "call_id": call_id, "direction": direction}

    logger.error("SmartFlo start metadata not found")
    return {"stream_id": "", "call_id": "", "direction": ""}


async def smartflo_bot(websocket):
    """Handle a SmartFlo telephony call using the same run_bot() pipeline."""
    call_data = await _parse_smartflo_start(websocket)
    if not call_data["stream_id"]:
        logger.error("Missing SmartFlo stream_id; aborting call")
        try:
            await websocket.close(code=1011)
        except Exception:
            pass
        return

    logger.info(
        "SmartFlo call started: stream_id={} call_id={} direction={}",
        call_data["stream_id"],
        call_data["call_id"],
        call_data.get("direction") or "unknown",
    )

    serializer = SmartFloFrameSerializer(
        stream_sid=call_data["stream_id"],
        call_sid=call_data["call_id"],
    )

    transport = FastAPIWebsocketTransport(
        websocket=websocket,
        params=FastAPIWebsocketParams(
            audio_in_enabled=True,
            audio_out_enabled=True,
            add_wav_header=False,
            serializer=serializer,
        ),
    )

    await run_bot(
        transport,
        is_telephony=True,
        smartflo_call_id=call_data["call_id"],
        smartflo_call_direction=call_data.get("direction", ""),
    )


